// Lingua corrente (default: italiano)
let _linguaCorrente = 'it';

// Ottieni traduzione per una chiave
function t(chiave) {
  const lingue = TRADUZIONI[_linguaCorrente] || TRADUZIONI.it;
  return lingue[chiave] || TRADUZIONI.it[chiave] || chiave;
}

// Cambia lingua e applica tutte le traduzioni
function cambiaLingua(codice) {
  if (!LINGUE_DISPONIBILI[codice]) return;
  _linguaCorrente = codice;

  const prefissoUtente = (typeof utenteCorrente !== 'undefined' && utenteCorrente)
    ? utenteCorrente.username : 'default';
  localStorage.setItem('lingua_' + prefissoUtente, codice);

  applicaDirezione(LINGUE_DISPONIBILI[codice].dir);
  applicaTraduzioni();

  const select = document.getElementById('select-lingua');
  if (select) select.value = codice;

  console.log('🌍 Lingua cambiata:', codice);
}

// Applica direzione LTR / RTL
function applicaDirezione(dir) {
  document.documentElement.setAttribute('dir', dir);
  document.documentElement.setAttribute('lang', _linguaCorrente);
  document.body.classList.toggle('rtl-mode', dir === 'rtl');
}

// Applica le traduzioni a tutti gli elementi con data-i18n
function applicaTraduzioni() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const chiave = el.getAttribute('data-i18n');
    const valore = t(chiave);
    if (valore) el.textContent = valore;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const chiave = el.getAttribute('data-i18n-placeholder');
    const valore = t(chiave);
    if (valore) el.placeholder = valore;
  });
}

// Carica lingua salvata
function caricaLinguaSalvata(username) {
  const utente = username || ((typeof utenteCorrente !== 'undefined' && utenteCorrente) ? utenteCorrente.username : 'default');
  const lingua = localStorage.getItem('lingua_' + utente) || 'it';
  cambiaLingua(lingua);
  return lingua;
}

// Popola la tendina lingua
function popolaTendinaLingua() {
  const select = document.getElementById('select-lingua');
  if (!select) return;
  select.innerHTML = '';
  Object.keys(LINGUE_DISPONIBILI).forEach(codice => {
    const l = LINGUE_DISPONIBILI[codice];
    select.innerHTML += `<option value="${codice}">${l.bandiera} ${l.nome}</option>`;
  });
  select.value = _linguaCorrente;
}

// Helper: nome mese tradotto
function tMese(numeroMese) {
  return t('mese_' + numeroMese);
}

// Helper: giorni settimana tradotti (array)
function tGiorniSettimana() {
  return [t('gio_sett_dom'), t('gio_sett_lun'), t('gio_sett_mar'),
          t('gio_sett_mer'), t('gio_sett_gio'), t('gio_sett_ven'), t('gio_sett_sab')];
}

